#include <iostream>
using namespace std;

int main() {
    // Chaque nombre intérieur est la somme des deux nombres au-dessus de lui.
    cout << 1 << "\n";
    cout << 1 << " " << 1 << "\n";
    cout << 1 << " " << 2 << " " << 1 << "\n";
    cout << 1 << " " << 3 << " " << 3 << " " << 1 << "\n";
    cout << 1 << " " << 4 << " " << 6 << " " << 4 << " " << 1 << "\n";
    cout << 1 << " " << 5 << " " << 10 << " " << 10 << " " << 5 << " " << 1 << "\n";
    cout << 1 << " " << 6 << " " << 15 << " " << 20 << " " << 15 << " " << 6 << " " << 1 << "\n";
    return 0;
}
