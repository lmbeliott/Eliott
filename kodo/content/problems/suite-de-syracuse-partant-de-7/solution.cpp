#include <iostream>
using namespace std;

int main() {
    // La suite calculée à la main : pair -> moitié, impair -> triple plus un.
    cout << 7 << " " << 22 << " " << 11 << " " << 34 << " " << 17 << " " << 52 << " "
         << 26 << " " << 13 << " " << 40 << " " << 20 << " " << 10 << " " << 5 << " "
         << 16 << " " << 8 << " " << 4 << " " << 2 << " " << 1 << "\n";
    // Le plus grand terme.
    cout << 52 << "\n";
    // Le nombre de termes.
    cout << 17 << "\n";
    return 0;
}
